export function translate(language: OverlayedConfig["language"], message: string): string {
  return language === "uk" ? (ukrainian[message] ?? message) : message;
}

export function useTranslation() {
  const { value: language } = useConfigValue("language");
  return (message: string) => translate(language, message);
}
